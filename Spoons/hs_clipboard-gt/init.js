// Right-clicking a row offers what v1 put behind its own context menu. The row is fixed
// when the menu is built, so every action closes over it.
function entryContextMenu(row) {
    return [
        {title: "Paste all up to here, tab separated", action: () => entriesPaste(row, "\t")},
        {title: "Paste all up to here, one per line", action: () => entriesPaste(row, "\n")},
        {type: "divider"},
        {title: "Delete entry", action: () => entryDelete(row)},
        {title: "Move entry to top", action: () => entryMoveToTop(row)},
        {title: "Move entry up", action: () => entryMoveUp(row)},
        {title: "Move entry down", action: () => entryMoveDown(row)},
        {title: "Invert order above", action: () => entriesInvert(row)}
    ]
}

function chooserChoices() {
    const choices = []

    history.forEach((entry, row) => {
        if (entry.type === "image") {
            // The picture itself is the row's image, so the entry is recognisable without
            // reading anything. The chooser scales it to the row.
            choices.push({
                text: `${entry.width}x${entry.height} image`,
                subText: entry.path.split("/").pop(),
                image: HSImage.fromPath(entry.path),
                action: "pasteImage",
                data: entry.path,
                row: row,
                contextMenu: entryContextMenu(row)
            })
            return
        }

        const masked = config.passwordsHide && passwordLike(entry.content)
        const revealed = revealAll || revealedRow === row
        const text = (masked && !revealed)
            ? `[hidden - ${entry.content.length} chars]`
            : entry.content.slice(0, config.displayMaxLength)

        choices.push({
            text: text,
            action: "paste",
            data: entry.content,
            row: row,
            contextMenu: entryContextMenu(row)
        })
    })

    if (choices.length === 0) {
        choices.push({
            text: "",
            subText: "《Clipboard is empty》",
            action: "none",
            image: HSImage.fromName("NSCaution")
        })
    } else {
        choices.push({
            text: "《Clear Clipboard History》",
            action: "clear",
            image: HSImage.fromName("NSTrashFull")
        })
    }

    choices.push({
        text: `《${pasteOnSelect ? "Disable" : "Enable"} Paste-on-select》`,
        action: "pasteOnSelect",
        // v1 used NSSwitchEnabledOn/Off, which this macOS no longer resolves.
        image: HSImage.fromSymbol(pasteOnSelect ? "checkmark.circle.fill" : "circle")
    })

    return choices
}

function chooserRefresh() {
    if (chooser) chooser.setChoices(chooserChoices())
    return module.exports
}

function chooserSelect(choice) {
    revealKeysDisable()
    revealReset()

    if (!choice) return

    if (choice.action === "clear") {
        historyClear()
        return
    }
    if (choice.action === "pasteOnSelect") {
        pasteOnSelectToggle()
        chooserRefresh()
        return
    }
    previewPollStop()
    previewHide()

    if (choice.action === "pasteImage" && typeof choice.data === "string") {
        const image = HSImage.fromPath(choice.data)
        if (!image) {
            hs.ui.alert("That image is no longer on disk").duration(2).show()
            return
        }
        lastImageWritten = choice.data
        lastImageWrittenSize = image.size
            ? {w: Math.round(image.size.w), h: Math.round(image.size.h)}
            : null
        hs.pasteboard.writeImage(image)
        if (previousWindow) previousWindow.focus()
        if (pasteOnSelect) {
            hs.timer.doAfter(config.pasteDelay, () => hs.eventtap.keyStroke(["cmd"], "v"))
        }
        return
    }

    if (choice.action !== "paste" || typeof choice.data !== "string") return

    hs.pasteboard.writeString(choice.data)
    if (previousWindow) previousWindow.focus()
    if (pasteOnSelect) {
        hs.timer.doAfter(config.pasteDelay, () => hs.eventtap.keyStroke(["cmd"], "v"))
    }
}

// MARK: - Lifecycle

function start() {
    if (chooser) return module.exports

    hs.fs.mkdir(config.clipboardDir)

    // An earlier version kept the history under logs/. Moved, rather than read in place,
    // so that everything this Spoon owns ends up in one directory.
    if (!hs.fs.exists(config.historyFile) && hs.fs.exists(config.historyFileWas)) {
        if (hs.fs.move(config.historyFileWas, config.historyFile)) {
            console.log(`[hs_clipboard-gt] history moved to ${config.historyFile}`)
        } else {
            console.error(`[hs_clipboard-gt] could not move ${config.historyFileWas}`)
        }
    }
    historyLoad()
    // Rewrite at once, so that anything password-like left on disk by an earlier run is
    // scrubbed whether or not something is copied this session.
    historySave()

    chooser = hs.chooser.create()
    chooser.placeholder = "Clipboard history"
    chooser.onSelect = chooserSelect
    chooser.onShow = () => {
        revealKeysEnable()
        previewPollStart()
    }
    chooser.onHide = () => {
        revealKeysDisable()
        revealReset()
        previewPollStop()
        previewHide()
        // Rebuild at once, so a revealed entry is not left in the chooser's own list.
        chooserRefresh()
    }
    chooser.setChoices(chooserChoices())

    revealCurrentHotkey = hs.hotkey.create(config.revealCurrentKey.mods, config.revealCurrentKey.key,
        () => passwordRevealCurrent(), null)
    revealAllHotkey = hs.hotkey.create(config.revealAllKey.mods, config.revealAllKey.key,
        () => passwordsRevealToggle(), null)

    hs.pasteboard.watcherInterval = config.watchInterval
    watcher = () => pasteboardCapture()
    hs.pasteboard.addWatcher(watcher)

    if (config.menubarShow) {
        menubarItem = hs.menubar.create(false)
        menubarItem.title = config.menubarTitle
        menubarItem.setClickCallback(() => historyToggle())
    }

    return module.exports
}

function stop() {
    previewPollStop()
    previewHide()
    if (watcher) {
        hs.pasteboard.removeWatcher(watcher)
        watcher = null
    }
    if (chooser) {
        chooser.hide()
        chooser = null
    }
    if (revealCurrentHotkey) {
        revealCurrentHotkey.destroy()
        revealCurrentHotkey = null
    }
    if (revealAllHotkey) {
        revealAllHotkey.destroy()
        revealAllHotkey = null
    }
    if (menubarItem) {
        menubarItem.destroy()
        menubarItem = null
    }
    revealReset()
    return module.exports
}

function historyShow() {
    if (!chooser) {
        console.error("[hs_clipboard-gt] historyShow() before start()")
        return module.exports
    }
    previousWindow = hs.window.focusedWindow()
    chooserRefresh()
    chooser.show()
    return module.exports
}

function historyHide() {
    if (chooser) chooser.hide()
    return module.exports
}

function historyToggle() {
    if (!chooser) return historyShow()
    return chooser.isVisible ? historyHide() : historyShow()
}

// Reading accessors, for commands and for the console.
function historyEntries() {
    return history.map((entry) => entry.type === "image"
        ? `[image ${entry.width}x${entry.height}] ${entry.path}`
        : entry.content)
}

function pasteOnSelectEnabled() {
    return pasteOnSelect
}

