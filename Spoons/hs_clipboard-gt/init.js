// MARK: - Password detection

// Shannon entropy of a string, in bits per character.
function passwordEntropy(text) {
    if (!text || text.length === 0) return 0

    const counts = new Map()
    for (const character of text) counts.set(character, (counts.get(character) || 0) + 1)

    let entropy = 0
    for (const count of counts.values()) {
        const p = count / text.length
        entropy -= p * Math.log2(p)
    }
    return entropy
}

const PASSWORD_SYMBOLS = /[!@#$%^&*()\-_=+[\]{}|;:',.<>?/\\`~"]/
// Above this share of digits, or of hex characters, a string is an identifier of some
// kind rather than a password.
const PASSWORD_MOSTLY = 0.70

// Step 1: shapes that are never masked, however random they look.
function passwordAllowlisted(text) {
    const length = text.length

    if ((text.match(/\n/g) || []).length > config.passwordMaxNewlines) return true

    // UUID.
    if (/^[0-9a-fA-F]{1,8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/.test(text)) return true
    // ULID: 26 characters of Crockford Base32.
    if (length === 26 && /^[0-9A-HJKMNP-TV-Z]+$/.test(text)) return true
    // MD5, SHA1 or SHA256 written out in hex.
    if ((length === 32 || length === 40 || length === 64) && /^[0-9a-fA-F]+$/.test(text)) return true
    // Base64 with padding.
    if (length % 4 === 0 && /=+$/.test(text) && /^[A-Za-z0-9+/]+=*$/.test(text)) return true
    // A number.
    if (/^-?[0-9]+\.?[0-9]*$/.test(text)) return true
    // An ISO date, with or without a time after it.
    if (/^\d{4}-\d{2}-\d{2}/.test(text)) return true
    // IPv4, and IPv6 taken as hex with at least two colons in it.
    if (/^\d+\.\d+\.\d+\.\d+$/.test(text)) return true
    if (/^[0-9a-fA-F:]+$/.test(text) && /:.*:/.test(text)) return true
    // A URL, a path, or a bare filename.
    if (text.includes("://")) return true
    if (text.includes("/")) return true
    if (/\.[a-zA-Z0-9]+$/.test(text) && !/\s/.test(text)) return true

    return false
}

// Step 2: long enough, unbroken, and mixed enough to be a password.
function passwordStructured(text) {
    const length = text.length
    if (length < config.passwordMinLength) return false
    if (/\s/.test(text)) return false

    let digits = 0
    let hex = 0
    let lower = false
    let upper = false
    let digit = false
    let symbol = false

    for (const character of text) {
        if (/[0-9]/.test(character)) {
            digits += 1
            hex += 1
            digit = true
        } else if (/[a-f]/.test(character)) {
            hex += 1
            lower = true
        } else if (/[A-F]/.test(character)) {
            hex += 1
            upper = true
        } else if (/[a-z]/.test(character)) {
            lower = true
        } else if (/[A-Z]/.test(character)) {
            upper = true
        } else if (PASSWORD_SYMBOLS.test(character)) {
            symbol = true
        }
    }

    if (digits / length >= PASSWORD_MOSTLY) return false
    if (hex / length >= PASSWORD_MOSTLY) return false

    const classes = [lower, upper, digit, symbol].filter(Boolean).length
    return classes >= 2
}

// All three steps. Only a string that clears every one of them is treated as a password.
function passwordLike(text) {
    if (typeof text !== "string" || text === "") return false
    if (passwordAllowlisted(text)) return false
    if (!passwordStructured(text)) return false
    return passwordEntropy(text) >= config.passwordEntropyThreshold
}

// The preview canvas beside the chooser, the row it is showing, and the timer that reads
// the selection. Held so they cannot be collected before they are used again.
