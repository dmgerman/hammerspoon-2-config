// ⌘R: reveal the selected row, or hide it again if it is the one already revealed.
function passwordRevealCurrent() {
    if (!chooser) return module.exports
    const row = chooser.selectedRow
    if (row === null || row === undefined || row < 0) return module.exports

    revealedRow = revealedRow === row ? null : row
    chooserRefresh()
    chooser.selectedRow = row
    return module.exports
}

// ⇧⌘R: reveal every masked entry, or mask them all again.
function passwordsRevealToggle() {
    if (!chooser) return module.exports
    const row = chooser.selectedRow

    revealAll = !revealAll
    revealedRow = null
    chooserRefresh()
    if (row !== null && row !== undefined && row >= 0) chooser.selectedRow = row
    return module.exports
}

