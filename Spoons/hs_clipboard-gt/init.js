// hs_clipboard-gt — a history of what has been copied, offered back through a chooser.
//
// A port of ClipboardTool.spoon (Alfred Schilken, MIT), itself derived from
// TextClipboardHistory.spoon and from code by VFS and asmagill, plus the password
// detection added to the local copy of it.
//
//     const clipboard = hs.loadSpoon("hs_clipboard-gt")
//     clipboard.start()
//     hs.hotkey.bind(hyper, "v", () => clipboard.historyShow(), null)
//
// Every string that reaches the pasteboard is prepended to the history, duplicates are
// collapsed by MD5, and the list is capped at config.historySize. Selecting an entry
// copies it back, and optionally types ⌘V into whatever window had focus.
//
// Entries that look like passwords are kept for the session but are never written to
// disk, and are shown as "[hidden - N chars]" until revealed with ⌘R (the selected row)
// or ⇧⌘R (all of them). Detection runs in three steps — an allowlist of shapes that are
// never passwords, a structural filter, and a Shannon entropy threshold — so that URLs,
// UUIDs, hashes and filenames are not masked.
//
// Four departures from the v1 Spoon:
//   * Changes arrive through hs.pasteboard.addWatcher rather than a timer of the Spoon's
//     own, so config.watchInterval sets the interval of the shared pasteboard watcher.
//   * The history is a JSON file under logs/, not an entry in the application defaults.
//   * Images are not stored. v1 kept them URL-encoded in the same list.
//   * There is no hs.dialog, so an entry longer than config.maxEntrySize is truncated
//     when it is stored instead of prompting. v1's max-size toggle is gone with it.

